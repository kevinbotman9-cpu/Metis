#!/usr/bin/env node
/**
 * How much of each budgeted route's first-load JavaScript is the shared shell,
 * and how much is the route — across commits, with Next's link prefetch on,
 * off, or both.
 *
 * Written on 2026-09-13, when the route budgets tripped and the obvious reading
 * ("the shell grew") was wrong: the shell had grown 0.8 kB, and the overrun was
 * the descriptor and panel registries loading whole on every route that touched
 * either (G-111). Kept because the question comes back whenever the budgets do,
 * and certainly when those registries are split.
 *
 * - The **shell** is the set of chunks every signed-in budgeted route loads.
 *   Everything else a route loads is the **route**.
 * - With prefetch **off**, requests Next marks as a router prefetch are aborted,
 *   so a route is measured without the screens it links to.
 *
 * Measures the same way `tests/bundle/bundle-size.spec.ts` does — a production
 * build served standalone, a signed-in cold load, bodies not headers — using the
 * bundle config's own server. The spec it runs is generated for the run and
 * deleted afterwards, so `npm run test:bundle` never picks it up.
 *
 * Usage (from apps/console):
 *   node scripts/measure-route-payload.mjs                       # HEAD, prefetch on
 *   node scripts/measure-route-payload.mjs --prefetch both
 *   node scripts/measure-route-payload.mjs --commits main=origin/main,head=HEAD --out ./payload
 *
 * Checking out a commit other than HEAD needs a clean tracked tree; the script
 * refuses otherwise, and always returns to the branch it started on.
 */
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CONSOLE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = join(CONSOLE, 'tests', 'bundle', 'route-payload.generated.spec.ts');

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const commits = arg('commits', 'head=HEAD')
  .split(',')
  .map((pair) => pair.split('='))
  .map(([label, ref]) => ({ label, ref: ref ?? label }));
const modes = { on: ['on'], off: ['off'], both: ['on', 'off'] }[arg('prefetch', 'on')];
if (!modes) throw new Error('--prefetch is on, off or both');
const out = resolve(arg('out', join(tmpdir(), 'metis-route-payload')));
mkdirSync(out, { recursive: true });

const SPEC_SOURCE = `import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { login, ACCOUNTS } from '../e2e/helpers';

// Generated by scripts/measure-route-payload.mjs for one run, then deleted.
const OUT = process.env.ROUTE_PAYLOAD_OUT;
const PREFETCH = process.env.ROUTE_PAYLOAD_PREFETCH !== 'off';
const budgets = JSON.parse(readFileSync(resolve(__dirname, '../../bundle-budgets.json'), 'utf8'));
const result: Record<string, { chunks: Record<string, number>; prefetches: string[] }> = {};
const isPrefetch = (headers: Record<string, string>) => Object.keys(headers).some((k) => k.toLowerCase().includes('prefetch'));

test.describe.serial('route payload', () => {
  test.skip(!OUT, 'run by scripts/measure-route-payload.mjs only');
  for (const route of Object.keys(budgets.routes)) {
    test(route, async ({ page }) => {
      const chunks: Record<string, number> = {};
      const prefetches: string[] = [];
      const pending: Promise<void>[] = [];
      if (route !== '/login') await login(page, ACCOUNTS.marcus);
      await page.route('**/*', (r) => {
        if (!isPrefetch(r.request().headers())) return r.continue();
        prefetches.push(new URL(r.request().url()).pathname);
        return PREFETCH ? r.continue() : r.abort();
      });
      page.on('response', (res) => {
        const url = new URL(res.url());
        if (!url.pathname.includes('/_next/static/') || !url.pathname.endsWith('.js')) return;
        pending.push(res.body().then((b) => { chunks[url.pathname] = b.length; }).catch(() => {}));
      });
      await page.goto(route, { waitUntil: 'networkidle' });
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
      await Promise.all(pending);
      result[route] = { chunks, prefetches: [...new Set(prefetches)] };
      writeFileSync(String(OUT), JSON.stringify(result, null, 2));
    });
  }
});
`;

const git = (cmd) => execSync(`git ${cmd}`, { cwd: CONSOLE }).toString().trim();
const startBranch = git('rev-parse --abbrev-ref HEAD');
const needsCheckout = commits.some(({ ref }) => git(`rev-parse ${ref}`) !== git('rev-parse HEAD'));
if (needsCheckout && git('status --porcelain --untracked-files=no')) {
  throw new Error('Measuring another commit checks it out, and the tracked tree is not clean.');
}

writeFileSync(SPEC, SPEC_SOURCE);
const files = [];
try {
  for (const { label, ref } of commits) {
    if (needsCheckout) execSync(`git checkout -q --detach ${ref}`, { cwd: CONSOLE, stdio: 'inherit' });
    // A checkout may carry its own copy of the generated spec's directory; write it again.
    writeFileSync(SPEC, SPEC_SOURCE);
    for (const mode of modes) {
      const file = join(out, `${label}.prefetch-${mode}.json`);
      console.log(`\n== ${label} (${ref}), prefetch ${mode}`);
      try {
        execSync('npx playwright test --config playwright.bundle.config.ts tests/bundle/route-payload.generated.spec.ts', {
          cwd: CONSOLE,
          stdio: 'inherit',
          env: { ...process.env, ROUTE_PAYLOAD_OUT: file, ROUTE_PAYLOAD_PREFETCH: mode },
        });
      } catch {
        console.log(`   the run for ${label}, prefetch ${mode}, exited non-zero; whatever it recorded is reported`);
      }
      if (existsSync(file)) files.push({ label, mode, file });
    }
  }
} finally {
  rmSync(SPEC, { force: true });
  if (needsCheckout) execSync(`git checkout -q ${startBranch}`, { cwd: CONSOLE, stdio: 'inherit' });
}

// --- analysis ---------------------------------------------------------------
const kb = (b) => Math.round((b / 1024) * 10) / 10;
const sum = (xs) => xs.reduce((a, b) => a + b, 0);
const measured = {};
for (const { label, mode, file } of files) {
  const data = JSON.parse(readFileSync(file, 'utf8'));
  const authed = Object.keys(data).filter((r) => r !== '/login');
  const shell = authed.length ? Object.keys(data[authed[0]].chunks).filter((c) => authed.every((r) => c in data[r].chunks)) : [];
  const rows = {};
  for (const [route, { chunks, prefetches }] of Object.entries(data)) {
    const total = sum(Object.values(chunks));
    const shellBytes = route === '/login' ? 0 : sum(shell.map((c) => chunks[c] ?? 0));
    rows[route] = { total: kb(total), shell: kb(shellBytes), route: kb(total - shellBytes), prefetches };
  }
  measured[`${label}/${mode}`] = rows;
  console.log(`\n## ${label}, prefetch ${mode}: shell is ${shell.length} chunks`);
  for (const [route, r] of Object.entries(rows)) {
    console.log(
      `${route.padEnd(36)} total ${String(r.total).padStart(7)}  shell ${String(r.shell).padStart(7)}  route ${String(r.route).padStart(7)}  prefetched ${r.prefetches.length ? r.prefetches.join(' ') : '-'}`
    );
  }
}

const delta = (a, b) => {
  for (const route of Object.keys(b)) {
    if (!a[route]) continue;
    const d = (k) => String(Math.round((b[route][k] - a[route][k]) * 10) / 10).padStart(7);
    console.log(`${route.padEnd(36)} ${d('total')} ${d('shell')} ${d('route')}`);
  }
};
for (const mode of modes) {
  const labels = commits.map((c) => c.label).filter((l) => measured[`${l}/${mode}`]);
  for (let i = 1; i < labels.length; i++) {
    console.log(`\n## ${labels[i - 1]} -> ${labels[i]}, prefetch ${mode} (kB: total / shell / route)`);
    delta(measured[`${labels[i - 1]}/${mode}`], measured[`${labels[i]}/${mode}`]);
  }
}
if (modes.length === 2) {
  for (const { label } of commits) {
    if (!measured[`${label}/on`] || !measured[`${label}/off`]) continue;
    console.log(`\n## ${label}: what prefetch adds (on minus off, kB: total / shell / route)`);
    delta(measured[`${label}/off`], measured[`${label}/on`]);
  }
}
console.log(`\nRaw measurements: ${out}`);
